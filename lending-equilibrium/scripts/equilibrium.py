def section_f():
    d = 1e-4
    el_hi = float(vs.replenished_expected_loss(PD + d, vs.basel_other_retail_correlation(PD + d)))
    el_lo = float(vs.replenished_expected_loss(PD - d, vs.basel_other_retail_correlation(PD - d)))
    kappa = (el_hi - el_lo) / (2 * d)
    put("KappaLoss", f"{kappa:.2f}")
    put("GammaBackward", f"{(1 - F) / kappa:.2f}")       # lenders' yield bends back above this
    put("GammaProtectFortyFive", f"{0.45 / kappa:.2f}")  # the reserve keeps covering losses up to this
    put("GammaProtectSixtyFive", f"{0.65 / kappa:.2f}")


def write_key(by):
    b, y = by["base"], by["yield"]
    write_csv("key.csv", [{
        "pd": PD, "premium_bps": PREMIUM * 1e4, "apr": A_REF, "el": EL, "r_c": R_C,
        "a_free": ((E / U) + EL) / (1 - F), "r_max_lenders": 1 - F - E / (U * A_REF),
        "rhat_base": b["rhat"], "lo99": b["lo99"], "hi99": b["hi99"], "v45_base": b["v45"], "v55_base": b["v55"],
        "v65_base": b["v65"], "v45_yield": y["v45"], "v65_yield": y["v65"],
        "rhat_h10": by["h10"]["rhat"], "lo99_h10": by["h10"]["lo99"], "hi99_h10": by["h10"]["hi99"],
        "v45_h10": by["h10"]["v45"], "v65_h10": by["h10"]["v65"],
    }])


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    section_a()
    section_b()
    lm = section_c()
    by = section_d(lm)
    write_key(by)
    section_e()
    section_f()
    with open(OUT / "summary.tex", "w") as fh:
        fh.write(HEADER)
        for k, v in macros.items():
            fh.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
    print(f"wrote {len(macros)} macros; EL={EL:.4f} R_C={R_C:.4f} a_ref={A_REF:.4f}")


if __name__ == "__main__":
    main()
