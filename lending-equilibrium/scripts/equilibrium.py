def wait_days(w, u, cushion):
    """Days until a run of a fraction w of deposits is paid out (Proposition 5)."""
    q0 = (1 - u) + cushion
    return TERM_DAYS * max(w - q0, 0.0) / u


def u_liquid(w_run, wait_target, cushion):
    """Largest utilisation for which a run of w_run is paid within wait_target days."""
    return TERM_DAYS * (1 - w_run + cushion) / (TERM_DAYS - wait_target)


def section_e():
    rows = []
    for w in np.round(np.arange(0.0, 1.0001, 0.025), 3):
        rows.append({"w": float(w), "u70": wait_days(w, 0.70, 0.0), "u85": wait_days(w, 0.85, 0.0),
                     "u90": wait_days(w, 0.90, 0.0), "u85c": wait_days(w, 0.85, 0.10)})
    write_csv("liquidity_curve.csv", rows)
    put("WaitFull", f"{wait_days(1.0, U, 0.0):.0f}")
    put("WaitFullCushion", f"{wait_days(1.0, U, 0.10):.0f}")
    put("WaitHalf", f"{wait_days(0.5, U, 0.0):.1f}")
    put("WaitQuarter", f"{wait_days(0.25, U, 0.0):.1f}")
    put("WaitThreeQuarter", f"{wait_days(0.75, U, 0.0):.1f}")
    put("WaitHalfCap", f"{wait_days(0.5, 0.90, 0.0):.1f}")
    put("TermDays", f"{TERM_DAYS:.0f}")
    lines = []
    for w_run in (0.25, 0.50, 0.75):
        cells = []
        for target in (3, 7, 14):
            u_max = min(0.90, u_liquid(w_run, target, 0.0))
            a0 = (E / u_max + EL) / (1 - F)
            cells.append(f"{100 * u_max:.0f} & {pct(a0)}")
        lines.append(f"{100 * w_run:.0f} & " + " & ".join(cells) + " \\\\")
    write_tex("table_liquidity.tex", lines)
    put("UMaxHalfWeek", f"{100 * min(0.90, u_liquid(0.5, 7, 0.0)):.0f}")
    put("UMaxHalfWeekCushion", f"{100 * min(0.90, u_liquid(0.5, 7, 0.10)):.0f}")
    put("AFreeAtULiq", pct((E / min(0.90, u_liquid(0.5, 7, 0.0)) + EL) / (1 - F)))
    put("AFreeAtCap", pct((E / 0.90 + EL) / (1 - F)))


