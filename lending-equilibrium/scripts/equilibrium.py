    put("RHatHMax", f"{100 * max(hsummary[n]['rhat'] for n in hnames):.1f}")
    # The ten-year yield itself, at the production APR, by share (seed 0): what the build-up costs.
    put("YTenAtRC", pct(interp_p(ygrids[10][0.0], R_C, A_REF)))
