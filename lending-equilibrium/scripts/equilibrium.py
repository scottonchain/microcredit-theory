    put("VSixtyFiveYield", f"{y['v65']:.3f}")
    put("AFortyFiveYield", pct(y["a45"]))
    put("ASixtyFiveYield", pct(y["a65"]))
    safety_names = [n for n in by if n != "yield"]
    put("RHatMin", f"{100 * min(by[n]['rhat'] for n in safety_names):.1f}")
    put("RHatMax", f"{100 * max(by[n]['rhat'] for n in safety_names):.1f}")
    put("SeedGainTwo", f"{100 * (by['base_k2']['vmax'] / by['base']['vmax'] - 1):.1f}")
    put("SeedGainFive", f"{100 * (by['base_k5']['vmax'] / by['base']['vmax'] - 1):.1f}")
    put("RHatSeedTwo", f"{100 * by['base_k2']['rhat']:.1f}")
    put("RHatSeedFive", f"{100 * by['base_k5']['rhat']:.1f}")
    put("RHatAbarFive", f"{100 * by['abar5']['rhat']:.1f}")
    put("RHatAbarTwenty", f"{100 * by['abar20']['rhat']:.1f}")
    put("LoNinetyNine", f"{100 * b['lo99']:.1f}")
    put("HiNinetyNine", f"{100 * b['hi99']:.1f}")

    # Common holding period: lenders evaluate the expected average return over the same H years as
    # the safety criterion (and over 5 years), starting at launch with the seed as the reserve.
    pgrids = {10: grids, 5: {0.0: safety_grid(lm, 0.0, 5)}}
    ygrids = {10: {k: yield_grid(lm, k, 10) for k in (0.0, 0.02)}, 5: {0.0: yield_grid(lm, 0.0, 5)}}
