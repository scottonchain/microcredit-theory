def a_min(r, h):
    """Lowest APR at which lenders earn e + h in the long run (Proposition 1)."""
    free = ((E + h) / U + EL) / (1 - F)              # while the reserve share is free
    locked = (E + h) / (U * (1 - F - r))              # once a*r exceeds expected loss
    return max(free, locked)


