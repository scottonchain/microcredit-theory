N_SAFE = 200_000    # paths for the safety tables
N_GRID = 100_000    # paths for the equilibrium grids
RHO = vs.basel_other_retail_correlation(PD)
EL = float(vs.replenished_expected_loss(PD, RHO))   # expected loss per exposure-year, re-lent
R_C = EL / A_REF                                   # reserve share whose inflow equals expected loss

macros = {}


def pct(x, d=2):
    return f"{100 * float(x):.{d}f}"


def put(name, value):
    macros[name] = value


def write_csv(name, rows):
    with open(OUT / name, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)


def write_tex(name, lines):
    with open(OUT / name, "w") as fh:
        fh.write(HEADER)
        for line in lines:
            fh.write(line + "\n")


def losses(years, n, tag):
    """Annual loss rates per unit lent, shape (years, n), common to every parameter setting."""
    rng = np.random.default_rng(np.random.SeedSequence([SEED, tag]))
    out = np.empty((years, n))
    for t in range(years):
        p = vs.conditional_pd(PD, RHO, rng.standard_normal(n))
        out[t] = np.asarray(vs.replenished_default_rate(np.clip(p, 0.0, 1 - 1e-12)))
    return out


def lender_paths(lm, r, a, k, years):
    """Lenders' annual returns Y (years, n) per unit of deposits, and the reserve R after each year.

    The reserve starts at k (external seed, per unit of deposits), gains u*a*r a year, and pays
    u*L_t first; lenders bear the rest. Y_t = u a (1-f-r) - lenders' loss.
    """
    n = lm.shape[1]
    reserve = np.full(n, float(k))
    y = np.empty((years, n))
    res = np.empty((years, n))
    for t in range(years):
        loss = U * lm[t]
        avail = reserve + U * a * r
        lender_loss = np.maximum(loss - avail, 0.0)
        reserve = np.maximum(avail - loss, 0.0)
        y[t] = U * a * (1 - F - r) - lender_loss
        res[t] = reserve
    return y, res


def p_principal_loss(lm, r, a, k, years):
    """P(lenders' return is negative in some year <= years). Equal to P(u L_t > u a (1-f) + R_{t-1})."""
    reserve = np.full(lm.shape[1], float(k))
    hit = np.zeros(lm.shape[1], dtype=bool)
    for t in range(years):
        loss = U * lm[t]
        hit |= loss > U * a * (1 - F) + reserve
        reserve = np.maximum(reserve + U * a * r - loss, 0.0)
    return float(hit.mean())


def long_run_yield(a, r):
    """Lenders' long-run expected return per unit of deposits under the lock (pricing paper, Theorem 2)."""
    return U * (a * (1 - F) - max(EL, a * r))


