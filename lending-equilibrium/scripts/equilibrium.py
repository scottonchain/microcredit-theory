    write_csv("equilibrium_curves.csv", [
        {"r": float(r), **{f"a_{n}": 100 * float(curves[n][0][i]) for n in curves},
         **{f"v_{n}": float(curves[n][1][i]) for n in curves}}
        for i, r in enumerate(fine)
    ])
    write_csv("equilibrium_summary.csv", summary)
    by = {s["name"]: s for s in summary}

    def lab(s):
        abar = "$\\infty$" if s["abar"] is None else f"{100 * s['abar']:.0f}"
        return f"{s['eta']:g} & {100 * s['tau']:.1f} & {abar} & {100 * s['k']:.0f}"

    lines = []
    for name in ("yield", "base", "abar5", "abar20", "tau05", "tau2", "eta05", "eta2", "base_k2", "base_k5"):
        s = by[name]
        rhat = f"$\\le {100 * R_C:.1f}$" if name == "yield" else f"{100 * s['rhat']:.1f}"
        lines.append(
            f"{lab(s)} & {rhat} & {s['vmax']:.3f} & "
            f"{100 * s['lo99']:.1f}--{100 * s['hi99']:.1f} & {s['v45']:.3f} & {s['v55']:.3f} & {s['v65']:.3f} \\\\"
        )
    write_tex("table_equilibrium.tex", lines)
    mk_y = Market(grids[0.0], 1.0, 0.01, None)
