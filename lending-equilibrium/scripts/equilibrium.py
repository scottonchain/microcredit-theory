def section_c():
    lm = losses(H, N_SAFE, tag=11)
    grid = np.round(np.arange(0.0, 0.7001, 0.0125), 4)
    seeds = (0.0, 0.02, 0.05)
    rows = []
    check_err = 0.0
    mv = {}
    for r in grid:
        row = {"r": float(r)}
        for k in seeds:
            y, res = lender_paths(lm, r, A_REF, k, H)
            avg = y.mean(axis=0)
            p_neg = float((y.min(axis=0) < 0).mean())
            p_evt = p_principal_loss(lm, r, A_REF, k, H)
            assert abs(p_neg - p_evt) < 1e-12, (r, k, p_neg, p_evt)
            # Theorem 1 of the pricing paper with an external seed: sum Y = H u a (1-f) - sum u L - (R_H - k)
            lhs = y.sum(axis=0)
            rhs = H * U * A_REF * (1 - F) - (U * lm).sum(axis=0) - (res[-1] - k)
            check_err = max(check_err, float(np.max(np.abs(lhs - rhs))))
            tag = f"k{int(round(k * 100))}"
            row[f"p_{tag}"] = 100 * p_neg
            row[f"mean_{tag}"] = 100 * float(avg.mean())
            row[f"res_{tag}"] = 100 * float(res[-1].mean())
            if k == 0.0 and abs(r - 0.45) < 1e-9:
                for lam in (5, 20, 100):
                    mv[lam] = float(avg.mean() - lam / 2 * avg.var())
                put("MVVarFortyFive", f"{avg.var() * 1e4:.2f}")
        rows.append(row)
    assert check_err < 1e-9, check_err
    mant, expo = f"{check_err:.0e}".split("e")
    put("IdentityErr", f"{mant}\\times10^{{{int(expo)}}}")
    write_csv("safety_curve.csv", rows)
    by_r = {round(r["r"], 4): r for r in rows}

    def p_at(r, k):
        """Interpolated principal-loss probability on a fine r grid."""
        key = f"p_k{int(round(k * 100))}"
        xs = np.array([x["r"] for x in rows])
        ys = np.array([x[key] for x in rows])
        return float(np.interp(r, xs, ys)) / 100

    put("PTenAtRC", pct(p_at(R_C, 0.0), 1))
    put("PTenAtFortyFive", pct(p_at(0.45, 0.0), 1))
    put("PTenAtFifty", pct(p_at(0.50, 0.0), 1))
    put("PTenAtFiftyFive", pct(p_at(0.55, 0.0), 1))
    put("PTenAtSixtyFive", pct(p_at(0.65, 0.0), 1))
    put("PTenAtFortyFiveSeedTwo", pct(p_at(0.45, 0.02), 1))
    put("PTenAtFortyFiveSeedFive", pct(p_at(0.45, 0.05), 1))
    put("PTenAtRCSeedFive", pct(p_at(R_C, 0.05), 1))
    put("MeanFortyFive", f"{by_r[0.45]['mean_k0']:.2f}")
    put("MeanZero", f"{by_r[0.0]['mean_k0']:.2f}")
    put("ResTenRC", f"{np.interp(R_C, [x['r'] for x in rows], [x['res_k0'] for x in rows]):.1f}")
    put("MeanRC", f"{np.interp(R_C, [x['r'] for x in rows], [x['mean_k0'] for x in rows]):.2f}")
    put("ResTenFortyFive", f"{by_r[0.45]['res_k0']:.1f}")
    put("ResTenSixtyFive", f"{by_r[0.65]['res_k0']:.1f}")
    # Mean-variance penalty at r = 45%: negligible against the cost of the reserve.
    base = float(np.interp(0.45, [x['r'] for x in rows], [x['mean_k0'] for x in rows])) / 100
    for lam, name in ((5, "Five"), (20, "Twenty"), (100, "Hundred")):
        put(f"MVPen{name}", f"{1e4 * (base - mv[lam]):.1f}")

    lines = []
    for r in (0.30, R_C, 0.45, 0.50, 0.55, 0.60, 0.65):
        mean0 = float(np.interp(r, [x["r"] for x in rows], [x["mean_k0"] for x in rows]))
        res0 = float(np.interp(r, [x["r"] for x in rows], [x["res_k0"] for x in rows]))
        lines.append(
            f"{100 * r:.1f} & {pct(p_at(r, 0.0), 1)} & {pct(p_at(r, 0.02), 1)} & {pct(p_at(r, 0.05), 1)} & "
            f"{mean0:.2f} & {res0:.1f} \\\\"
        )
    write_tex("table_safety.tex", lines)

    # r_safe: smallest share on a fine grid with P <= alpha, by seed.
    fine = np.round(np.arange(0.0, 0.7001, 0.0025), 4)
    lines = []
    for alpha in (0.10, 0.05, 0.02):
        cells = []
        for k in seeds:
            hit = None
            for r in fine:
                if p_at(r, k) <= alpha:
                    hit = r
                    break
            cells.append("--" if hit is None else f"{100 * hit:.1f}")
        lines.append(f"{100 * alpha:.0f} & " + " & ".join(cells) + " \\\\")
    write_tex("table_rsafe.tex", lines)

    # Finite pools: with n loans the realised annual loss rate is a binomial count around the
    # conditional rate (the base case is the infinitely granular pool).
    rng = np.random.default_rng(np.random.SeedSequence([SEED, 13]))
    finite = {}
    for n_loans in (100, 1000):
        lmf = rng.binomial(n_loans, np.clip(lm, 0.0, 1.0)) / n_loans
        finite[n_loans] = {r: p_principal_loss(lmf, r, A_REF, 0.0, H) for r in (R_C, 0.45, 0.55, 0.65)}
    lines = []
    for r in (R_C, 0.45, 0.55, 0.65):
        lines.append(f"{100 * r:.1f} & {pct(finite[100][r], 1)} & {pct(finite[1000][r], 1)} & {pct(p_at(r, 0.0), 1)} \\\\")
    write_tex("table_finite_pool.tex", lines)
    put("PTenFortyFivePoolHundred", pct(finite[100][0.45], 1))
    put("PTenFortyFivePoolThousand", pct(finite[1000][0.45], 1))
    put("PTenRCPoolHundred", pct(finite[100][R_C], 1))

    # Seed against share: the seed that gives, at the free share R_C, the protection of a higher
    # share. Costs are compared over the same horizon H: the share costs lenders the difference in
    # mean return over the first H years (and u a (r - R_C) a year in the long run); the seed is a
    # gift that its funder never recovers, so its cost is the annuity that repays it at the hurdle
    # rate over H years.
    # Both costs are levelised with the same discount factors: the seed as the annuity that repays
    # it over H years at the hurdle h, k / A(h), and the share as the discounted sum of the yearly
    # differences in expected return divided by the same A(h), where A(h) = sum_t (1+h)^-t.
    disc = {E: (1 + E) ** -np.arange(1, H + 1), 0.15: 1.15 ** -np.arange(1, H + 1)}
    ann = {h: 1.0 / disc[h].sum() for h in disc}
    put("AnnuityAtE", f"{ann[E]:.3f}")
    put("AnnuityAtFifteen", f"{ann[0.15]:.3f}")
    path_rc = lender_paths(lm, R_C, A_REF, 0.0, H)[0].mean(axis=1)   # expected return by year at R_C
    lines = []
    for r in (0.45, 0.50, 0.55, 0.60, 0.65):
        target = p_at(r, 0.0)
        found = None
        for k in np.arange(0.0, 0.2001, 0.0025):
            lm_k = p_principal_loss(lm, R_C, A_REF, float(k), H)
            if lm_k <= target + 1e-12:
                found = float(k)
                break
        share_cost = U * A_REF * (r - R_C)            # yearly, per unit of deposits, lenders' yield forgone
        delta = path_rc - lender_paths(lm, r, A_REF, 0.0, H)[0].mean(axis=1)   # yearly cost over the first H years
        share_ten = {h: float(delta @ disc[h] / disc[h].sum()) for h in disc}  # levelised at the hurdle
        seed_cost = {h: (None if found is None else found * ann[h]) for h in disc}
        lines.append(
            f"{100 * r:.0f} & {pct(target, 1)} & " +
            ("--" if found is None else f"{100 * found:.2f}") + " & " + pct(share_cost) + " & " +
            pct(share_ten[E]) + " & " + pct(share_ten[0.15]) + " & " +
            ("--" if found is None else pct(seed_cost[E])) + " & " +
            ("--" if found is None else pct(seed_cost[0.15])) + " \\\\"
        )
        tag = {0.45: "FortyFive", 0.55: "FiftyFive"}.get(round(r, 2))
        if tag and found is not None:
            put(f"SeedEquiv{tag}", f"{100 * found:.2f}")
            put(f"SeedCost{tag}", pct(seed_cost[0.15]))
            put(f"SeedCostE{tag}", pct(seed_cost[E]))
            put(f"ShareCost{tag}", pct(share_cost))
            put(f"ShareCostTen{tag}", pct(float(delta.mean())))
            put(f"ShareCostTenE{tag}", pct(share_ten[E]))
            put(f"ShareCostTenH{tag}", pct(share_ten[0.15]))
    write_tex("table_seed.tex", lines)
    # Late repayment (Section 7): cash collected by the end of one term when a fraction of the
    # book pays late, per unit of deposits.
    put("LateShare", "10")
    put("LateCollectedByTerm", f"{1 - U + 0.9 * U:.3f}")
    put("LateRemaining", f"{0.1 * U:.3f}")
    return lm


